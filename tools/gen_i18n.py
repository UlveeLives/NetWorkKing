# Builds js/i18n.js from tools/strings/*.py (each line: K("key", az, tr, en, ru)).
import glob, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = {}
def K(k, az, tr, en, ru):
    if k in D: print("DUP", k, file=sys.stderr)
    D[k] = (az, tr, en, ru)
for f in sorted(glob.glob(os.path.join(ROOT, "tools", "strings", "*.py"))):
    exec(open(f, encoding="utf-8").read(), {"K": K})
out = "/*! NetWorkKing — © 2026 Ulvi Badalov. Bütün hüquqlar qorunur / All rights reserved. Proprietary — see LICENSE. */\n// Generated by tools/gen_i18n.py — edit tools/strings/*.py instead.\nconst I18N = {\n" + ",\n".join(f'{lg}: {json.dumps({k: v[i] for k, v in D.items()}, ensure_ascii=False)}' for i, lg in enumerate(["az","tr","en","ru"])) + "\n};\n"
open(os.path.join(ROOT, "js", "i18n.js"), "w", encoding="utf-8").write(out)
print(len(D), "keys")
# check: keys used in code
src = "".join(open(f, encoding="utf-8").read() for f in glob.glob(os.path.join(ROOT, "js", "**", "*.js"), recursive=True) if not f.endswith("i18n.js") and not f.endswith("catalog-data.js"))
used = set(re.findall(r'\bt\("([A-Za-z0-9_]+)"', src)) | set(re.findall(r'label:"([A-Za-z0-9_]+)"', src)) | set(re.findall(r'name:"(app_[a-z]+)"', src)) | set(re.findall(r'(?:desc|docName):"([a-z_]+)"', src))
wsrc = open(os.path.join(ROOT, "js", "apps", "wifi.js"), encoding="utf-8").read()
wused = set(re.findall(r'\bt\("([A-Za-z0-9_]+)"', wsrc))
miss = sorted(k for k in used if k not in D and "wf_" + k not in D and not k.endswith("_"))
if miss: print("MISSING", len(miss), " ".join(miss))
