# Builds the licence texts used by the program from legal/EULA.txt:
#   build/eula.txt   — shown by the Windows installer (UTF-8 with BOM, Windows line ends)
#   js/core/legal.js — shown in Settings → About
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
txt = open(os.path.join(ROOT, "legal", "EULA.txt"), encoding="utf-8").read().strip() + "\n"
open(os.path.join(ROOT, "build", "eula.txt"), "w", encoding="utf-8-sig", newline="\r\n").write(txt)
az, en = [x.strip() for x in txt.split("-" * 60)]
js = ("/*! NetWorkKing — © 2026 Ulvi Badalov. Bütün hüquqlar qorunur / All rights reserved. Proprietary — see LICENSE. */\n"
      "// Generated by tools/gen_legal.py from legal/EULA.txt — edit that file instead.\n\"use strict\";\n"
      "const COPYRIGHT = \"© 2026 Ulvi Badalov\";\n"
      "const EULA = " + json.dumps({"az": az, "en": en}, ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "js", "core", "legal.js"), "w", encoding="utf-8").write(js)
print("eula ok", len(az), len(en))
