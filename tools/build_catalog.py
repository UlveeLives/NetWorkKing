# Builds the device catalog from catalog/src/*.json (records in catalog/SCHEMA.md format):
#   catalog/catalog.json  — published file the app downloads for online updates
#   js/catalog-data.js    — built-in copy used offline
import glob, json, os, sys, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KINDS = set("firewall router coresw switch modem ont wlc ap server nas storage ups pdu camera nvr dvr monitor workstation pp fpp splice mediaconv phone printer other decoder encoder intercom access kvm poeinj tv".split())
recs, seen, errs = [], {}, []
for f in sorted(glob.glob(os.path.join(ROOT, "catalog", "src", "*.json"))):
    for r in json.load(open(f, encoding="utf-8")):
        b, m = str(r.get("brand") or "").strip(), str(r.get("model") or "").strip()
        if not b or not m: errs.append(f"{os.path.basename(f)}: record without brand/model"); continue
        if r.get("kind") not in KINDS: errs.append(f"{b} {m}: unknown kind {r.get('kind')}"); continue
        if not r.get("source"): errs.append(f"{b} {m}: no source"); continue
        k = (b + "|" + m).lower()
        if k in seen: errs.append(f"{b} {m}: duplicate (kept the first)"); continue
        seen[k] = 1; recs.append(r)
recs.sort(key=lambda r: (r["brand"].lower(), r["model"].lower()))
ver = datetime.date.today().isoformat()
os.makedirs(os.path.join(ROOT, "catalog"), exist_ok=True)
json.dump({"version": ver, "date": ver, "count": len(recs), "models": recs}, open(os.path.join(ROOT, "catalog", "catalog.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
open(os.path.join(ROOT, "js", "catalog-data.js"), "w", encoding="utf-8").write("/*! NetWorkKing — © 2026 Ulvi Badalov. Bütün hüquqlar qorunur / All rights reserved. Proprietary — see LICENSE. */\n// Generated by tools/build_catalog.py from catalog/src — do not edit by hand.\nwindow.CATALOG_DATA = " + json.dumps(recs, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(recs), "models"); [print("!", e) for e in errs]
